#!/usr/bin/env node
/**
 * Writes the two generated (gitignored) modules of the Angular examples app
 * (src/angular-app):
 *
 * - routes.generated.ts: one lazy route per `src/pages/**\/*.page.angular.ts`,
 *   with the URL Next.js gives the `.page.tsx` sibling (`tests/a/b`, an
 *   `index` page gets its folder's URL). Specs the parity allowlist skips
 *   as a whole (parity-allowlist.angular.json, entries without `test`) get
 *   no route.
 * - test-index.generated.ts: the test pages index (TestPagesIndex in
 *   src/angular-app/test-pages-index.ts) - the folder URLs that have an index
 *   in the React app (an `index.page.tsx`) and the tree of the routed Angular
 *   pages, the Angular version of what the Vue app gets from
 *   scripts/vite-plugin-test-pages-index.js.
 * - env.generated.ts: `process.env.NEXT_PUBLIC_*` for the pages (the test
 *   pages read them as the React ones do), from the same .env files Next.js
 *   reads, plus this checkout's ports (scripts/dev-ports.cjs), and the
 *   `__DEV__` / `__VERSION__` / `__VERSION_TIMESTAMP__` globals that the
 *   library sources imported through `@src/*` read. It contains the license
 *   key: never commit it.
 *
 *   node scripts/generate-angular-app.js          # production env files
 *   node scripts/generate-angular-app.js --dev    # development env files
 *   node scripts/generate-angular-app.js --watch  # rewrites the routes when
 *                                                 # pages are added or
 *                                                 # removed (the env file
 *                                                 # only when missing)
 *
 * Run it through ../scripts/with-ports.mjs (the package scripts do), so the
 * data URL points at this checkout's data server.
 */
const fs = require('fs');
const path = require('path');

const { getPort, localDataUrl } = require('../../scripts/dev-ports.cjs');

const EXAMPLES_ROOT = path.resolve(__dirname, '..');
const PAGES_DIR = path.join(EXAMPLES_ROOT, 'src', 'pages');
const APP_DIR = path.join(EXAMPLES_ROOT, 'src', 'angular-app');
const ALLOWLIST_FILE = path.join(
  EXAMPLES_ROOT,
  'parity-allowlist.angular.json',
);
const ROUTES_FILE = path.join(APP_DIR, 'routes.generated.ts');
const ENV_FILE = path.join(APP_DIR, 'env.generated.ts');
const TEST_INDEX_FILE = path.join(APP_DIR, 'test-index.generated.ts');

const PAGE_EXT = '.page.angular.ts';

const watch = process.argv.includes('--watch');
const mode =
  watch || process.argv.includes('--dev') ? 'development' : 'production';

const HEADER = `// Generated by examples/scripts/generate-angular-app.js - do not edit.
// Gitignored (/examples/src/angular-app/*.generated.ts).
`;

/** writes `file` only when its contents change (no needless rebuilds in watch mode) */
function writeIfChanged(file, contents) {
  let current = null;
  try {
    current = fs.readFileSync(file, 'utf8');
  } catch {}
  if (current === contents) return false;
  fs.writeFileSync(file, contents);
  return true;
}

/** `tests/a/b.page.angular.ts` files, relative to src/pages */
function listPages(dir = PAGES_DIR, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) listPages(full, out);
    else if (entry.name.endsWith(PAGE_EXT)) {
      out.push(path.relative(PAGES_DIR, full).split(path.sep).join('/'));
    }
  }
  return out.sort();
}

/** specs (`tests/a/b.spec.ts`) that are skipped as a whole on Angular */
function excludedSpecs() {
  let allowlist;
  try {
    allowlist = JSON.parse(fs.readFileSync(ALLOWLIST_FILE, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return new Set();
    throw new Error(
      `${path.relative(EXAMPLES_ROOT, ALLOWLIST_FILE)}: ${error.message}`,
    );
  }
  return new Set(
    (allowlist.entries || [])
      .filter((entry) => entry.spec && !entry.test)
      .map((entry) => entry.spec),
  );
}

function routesModule() {
  const excluded = excludedSpecs();
  const routes = [];
  for (const page of listPages()) {
    const base = page.slice(0, -PAGE_EXT.length);
    if (excluded.has(base + '.spec.ts')) {
      console.warn(
        `[angular-app] ${page}: its spec is in parity-allowlist.angular.json (skipped on Angular), so the page gets no route`,
      );
      continue;
    }
    routes.push({
      path: base.replace(/(^|\/)index$/, ''),
      importPath: '../pages/' + page.replace(/\.ts$/, ''),
    });
  }

  return `${HEADER}import type { Routes } from '@angular/router';

export const pageRoutes: Routes = [${routes
    .map(
      ({ path: routePath, importPath }) => `
  {
    path: ${JSON.stringify(routePath)},
    loadComponent: () => import(${JSON.stringify(importPath)}),
  },`,
    )
    .join('')}${routes.length ? '\n' : ''}];
`;
}

/**
 * The index of the test pages: the folder URLs with an index (the ones the
 * React and Vue apps have) and every entry under src/pages, as the React and
 * Vue indexes list them (scripts/buildTestPagesIndexProps.js), for the
 * Angular pages that have a route. Folders without one are left out.
 */
function testIndexModule() {
  const {
    buildTestPagesIndexProps,
    collectTestIndexRoutePaths,
  } = require('./buildTestPagesIndexProps');

  const excluded = excludedSpecs();
  const { entries } = buildTestPagesIndexProps('', {
    pagesRoot: PAGES_DIR,
    pageSuffix: PAGE_EXT,
    // the pages that have a route (routesModule)
    includePage: (pagePath) => !excluded.has(pagePath + '.spec.ts'),
  });

  return `${HEADER}import type { IndexNode } from '../test-index/TestPagesIndex.types';

/** the folder URLs that show the index ('/', '/tests', '/tests/table', ...) */
export const testIndexRoutes: string[] = ${JSON.stringify(
    collectTestIndexRoutePaths(PAGES_DIR),
  )};

/** the tree of the folders and pages under src/pages */
export const testIndexEntries: IndexNode[] = ${JSON.stringify(entries)};
`;
}

/** KEY=value lines of a .env file (the subset Next.js and Vite agree on) */
function parseEnvFile(file) {
  let text;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch {
    return {};
  }
  const values = {};
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([\w.-]+)\s*=\s*(.*?)\s*$/);
    if (!match) continue;
    let value = match[2];
    const quoted = value.match(/^(['"])(.*)\1$/);
    if (quoted) value = quoted[2];
    else value = value.replace(/\s+#.*$/, '');
    values[match[1]] = value;
  }
  return values;
}

function envModule() {
  // the order of precedence Next.js uses (later wins), the environment last
  const fromFiles = Object.assign(
    {},
    ...['.env', `.env.${mode}`, '.env.local', `.env.${mode}.local`].map(
      (name) => parseEnvFile(path.join(EXAMPLES_ROOT, name)),
    ),
  );
  const env = {};
  for (const source of [fromFiles, process.env]) {
    for (const [key, value] of Object.entries(source)) {
      if (key.startsWith('NEXT_PUBLIC_') && value !== undefined) {
        env[key] = value;
      }
    }
  }

  // this checkout's data server (with-ports.mjs puts it in the environment;
  // the same redirect when the script runs on its own)
  if (!process.env.NEXT_PUBLIC_BASE_URL) {
    const dataUrl = localDataUrl(getPort('data'), EXAMPLES_ROOT);
    if (dataUrl) env.NEXT_PUBLIC_BASE_URL = dataUrl;
  }
  // the links between the React, Vue and Angular apps (src/test-index)
  env.NEXT_PUBLIC_EXAMPLES_PORT = String(getPort('examples'));
  env.NEXT_PUBLIC_EXAMPLES_VUE_PORT = String(getPort('examplesVue'));
  env.NEXT_PUBLIC_EXAMPLES_ANGULAR_PORT = String(getPort('examplesAngular'));
  env.NEXT_PUBLIC_EXAMPLES_DEV_PORT = String(getPort('examplesDev'));
  env.NEXT_PUBLIC_TEST_RUNNER_PORT = String(getPort('testRunner'));

  const sorted = Object.fromEntries(
    Object.entries(env).sort(([a], [b]) => a.localeCompare(b)),
  );

  return `${HEADER}// Contains the license key: never commit it.
//
// Imported first by main.ts. The test pages read process.env.NEXT_PUBLIC_*
// as their React siblings do (Next.js inlines them, Vite defines them).

const env: Record<string, string> = ${JSON.stringify(sorted, null, 2)};

const g = globalThis as any;
g.process = g.process || {};
g.process.env = Object.assign(g.process.env || {}, env);

// read by the library sources that pages import through @src/* (the
// library's own dev build has them compiled in)
g.__DEV__ = true;
g.__VERSION__ = ${JSON.stringify(require('../../package.json').version)};
// as if the source was published now (like the Vue app's vite.config.ts)
g.__VERSION_TIMESTAMP__ = ${Date.now()};

export {};
`;
}

function generateRoutes() {
  for (const [file, contents] of [
    [ROUTES_FILE, routesModule()],
    [TEST_INDEX_FILE, testIndexModule()],
  ]) {
    if (writeIfChanged(file, contents)) {
      console.log(`[angular-app] wrote ${path.relative(EXAMPLES_ROOT, file)}`);
    }
  }
}

fs.mkdirSync(APP_DIR, { recursive: true });
generateRoutes();
// the env file has a timestamp: in watch mode it's written once (by the
// `--dev` run before it), not again on every start of the watcher
if (!watch || !fs.existsSync(ENV_FILE)) {
  writeIfChanged(ENV_FILE, envModule());
  console.log(
    `[angular-app] wrote ${path.relative(EXAMPLES_ROOT, ENV_FILE)} (${mode})`,
  );
}

if (watch) {
  let timer = null;
  const schedule = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        generateRoutes();
      } catch (error) {
        console.error(`[angular-app] ${error.message}`);
      }
    }, 100);
  };
  fs.watch(PAGES_DIR, { recursive: true }, (_event, filename) => {
    // the pages, and the React index pages (the folders with an index)
    if (
      filename &&
      (filename.endsWith(PAGE_EXT) || filename.endsWith('index.page.tsx'))
    ) {
      schedule();
    }
  });
  fs.watchFile(ALLOWLIST_FILE, { interval: 1000 }, schedule);
  console.log(`[angular-app] watching src/pages for ${PAGE_EXT} files`);
}
