// The docs page of both URL trees: `/docs/...` (React) and `/vue/docs/...`.
// One markdown file per page; the framework decides the links, the demos,
// the sidebar and the metadata.
import { mapRouteTree } from '@thedatagrid/docs-kit/frameworks';
import type { Metadata } from 'next';
import { redirect } from 'next/navigation';

import { CenterContent } from '@www/app/CenterContent';
import { metadata as meta } from '@www/app/metadata';
import { CopyMarkdownButton } from '@www/components/CopyMarkdownButton';
import { DocsFrameworkBanner } from '@www/components/DocsFrameworks';
import { Page, type RouteItem } from '@www/components/Layout/Page';
import { Toc } from '@www/components/Layout/Toc';
import PageHeading from '@www/components/PageHeading';
import { renderMarkdownPage } from '@www/components/renderMarkdownPage';
import { siteContent } from '@www/content';
import sidebarLearn from '@www/sidebarLearn.json';
import sidebarReference from '@www/sidebarReference.json';
import sidebarReleases from '@www/sidebarReleases.json';
import { asMeta } from '@www/utils/asMeta';
import {
  docsHasPage,
  getDocsPage,
  getDocsPageMeta,
  getDocsPagePaths,
  textForFramework,
} from '@www/utils/docsFrameworkContent';
import { contentForFramework } from '@www/utils/docsFrameworkPages';
import {
  docsFrameworks,
  type DocsFrameworkId,
} from '@www/utils/docsFrameworks';
import {
  getMarkdownHeadingsForPage,
  getPropHeadings,
  type TocHeading,
} from '@www/utils/getMarkdownHeadings';

const SITE_URL = 'https://infinite-table.com';

/** `['learn', 'sorting']` → `/docs/learn/sorting`, the page's path in the React form. */
const neutralPathOf = (slug: string[]) => ['/docs', ...slug].join('/');

/** `generateStaticParams` of a framework's `[...docsPages]` route: the pages below `/docs`. */
export function docsStaticParams(framework: DocsFrameworkId) {
  return getDocsPagePaths(framework)
    .map((path) => ({ docsPages: path.split('/').slice(2).filter(Boolean) }))
    .filter((params) => params.docsPages.length > 0);
}

export function docsPageMetadata(
  framework: DocsFrameworkId,
  slug: string[],
): Metadata {
  const neutralPath = neutralPathOf(slug);
  const page = getDocsPage(neutralPath);
  const pageMeta = getDocsPageMeta(page, framework);
  const suffix = `Infinite Table ${docsFrameworks.label(framework)} DataGrid`;
  // the docs index keeps the site-wide docs title (and, for React, as it was: without the suffix)
  let title = `${pageMeta.title ?? meta.title} | ${suffix}`;
  if (!slug.length) {
    title =
      framework === docsFrameworks.default
        ? meta.title
        : `${meta.title} | ${suffix}`;
  }

  return asMeta({
    title,
    description:
      pageMeta.description ?? textForFramework(meta.description, framework),
    // each framework's page is its own canonical: the code on it differs
    alternates: {
      canonical: `${SITE_URL}${docsFrameworks.pathFor(neutralPath, framework)}`,
    },
  });
}

export async function DocsRoutePage(props: {
  framework: DocsFrameworkId;
  slug: string[];
}) {
  const { framework, slug } = props;
  const neutralPath = neutralPathOf(slug);
  const page = docsHasPage(neutralPath, framework)
    ? getDocsPage(neutralPath)!
    : siteContent.paths['/404'];

  if (page.frontmatter.redirect_to) {
    redirect(page.frontmatter.redirect_to);
  }

  // .md sibling generated by www/scripts/generate-llms-docs.js (React pages only)
  let mdPath: string | null = null;
  if (framework === docsFrameworks.default) {
    if (siteContent.paths[neutralPath]) {
      mdPath = `${neutralPath}.md`;
    } else if (siteContent.paths[`${neutralPath}/`]) {
      mdPath = `${neutralPath}/index.md`;
    }
  }

  let sidebar: RouteItem[] = sidebarLearn;
  if (neutralPath.startsWith('/docs/reference')) {
    sidebar = sidebarReference;
  }
  if (neutralPath.startsWith('/docs/releases')) {
    sidebar = sidebarReleases;
  }
  const isReference = sidebar === sidebarReference;
  // without the sections written for the other framework
  const content = contentForFramework(page.content, framework);
  const anchors: TocHeading[] = isReference
    ? getPropHeadings(content)
    : getMarkdownHeadingsForPage(content);

  // the sidebar of another framework: its own pages, and the React page
  // (marked) where it has none yet
  const routeTree =
    framework === docsFrameworks.default
      ? sidebar
      : mapRouteTree(docsFrameworks, sidebar, framework, docsHasPage, {
          onFallback: (route, fallback) => ({
            ...route,
            frameworkFallback: docsFrameworks.label(fallback),
          }),
        });

  const pageMeta = getDocsPageMeta(page, framework);

  return (
    <Page routeTree={routeTree}>
      <CenterContent>
        <DocsFrameworkBanner className="mb-6" />
        <PageHeading
          title={pageMeta.title ?? page.frontmatter.title}
          since={page.frontmatter.since}
        ></PageHeading>
        {mdPath ? <CopyMarkdownButton mdPath={mdPath} /> : null}
        {await renderMarkdownPage({
          slug: ['docs', ...slug],
          baseUrl: import.meta.url,
          framework,
        })}
      </CenterContent>
      {anchors.length ? (
        <div className="w-full lg:max-w-xs hidden 2xl:block">
          <Toc headings={anchors} noHighlight={isReference} />
        </div>
      ) : null}
    </Page>
  );
}
