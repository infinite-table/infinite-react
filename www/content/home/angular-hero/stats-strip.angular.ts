import {
  ChangeDetectionStrategy,
  Component,
  DestroyRef,
  computed,
  inject,
  input,
  signal,
} from '@angular/core';

import {
  HeroFeed,
  type FeedStats,
} from '../../../src/components/hero/data/feed';
import { formatInt } from '../../../src/components/hero/format';

/** Live counters, updated twice a second. */
@Component({
  selector: 'div[heroStatsStrip]',
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: {
    class: 'hero-stats',
    '[attr.role]': "building() ? 'status' : null",
    '[attr.aria-live]': "building() ? null : 'off'",
  },
  template: `
    @if (building(); as building) {
      <span class="hero-stats__dot hero-stats__dot--busy" aria-hidden="true"></span>
      {{ building }}
    } @else {
      <span
        class="hero-stats__dot"
        [class.hero-stats__dot--live]="stats().running"
        aria-hidden="true"
      ></span>
      <span class="hero-stats__label">
        {{ stats().running ? 'LIVE' : 'PAUSED' }}
      </span>
      <span class="hero-stat" title="Price ticks generated by the worker">
        <span class="hero-stat__value hero-num">
          {{ format(stats().ticksPerSecond) }}
        </span>
        <span class="hero-stat__unit">ticks/s</span>
      </span>
      <span
        class="hero-stat"
        title="Rows updated in the grid per second, after coalescing ticks per frame"
      >
        <span class="hero-stat__value hero-num">
          {{ format(stats().updatesPerSecond) }}
        </span>
        <span class="hero-stat__unit">row updates/s</span>
      </span>
      <span class="hero-stat" title="Frames per second on this page">
        <span class="hero-stat__value hero-num">{{ stats().fps }}</span>
        <span class="hero-stat__unit">fps</span>
      </span>
      <span
        class="hero-stat"
        title="Main-thread time for one DataSource commit (re-index, re-sort, regroup, render). Above ~5ms, commits are spaced out automatically to keep the frame rate; with 100k+ rows they also wait while you scroll."
      >
        <span class="hero-stat__value hero-num">{{ commitMs() }}</span>
        <span class="hero-stat__unit">{{ commitUnit() }}</span>
      </span>
    }
  `,
})
export class StatsStrip {
  readonly building = input.required<string | null>();

  private readonly feed = inject(HeroFeed);
  protected readonly stats = signal<FeedStats>(this.feed.stats);
  protected readonly format = formatInt;

  protected readonly commitMs = computed(() => {
    const ms = this.stats().commitMs;
    return ms < 1 ? '<1' : ms < 10 ? ms.toFixed(1) : formatInt(ms);
  });

  protected readonly commitUnit = computed(() => {
    const { gridPaused, scrollHeld, flushIntervalMs } = this.stats();
    if (gridPaused)
      return 'ms/commit · grid updates paused at this size, ticks continue in the charts';
    if (scrollHeld) return 'ms/commit · held while scrolling';
    return flushIntervalMs > 0
      ? `ms/commit · every ${formatInt(flushIntervalMs)}ms`
      : 'ms/commit';
  });

  constructor() {
    inject(DestroyRef).onDestroy(
      this.feed.onStats((next) => this.stats.set(next)),
    );
  }
}
